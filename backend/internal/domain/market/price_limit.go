// PriceLimitWidth は基準値段に対する制限値幅(円)。基準値段が正でなければ 0 を返す
// — 0 を「制限なし」と読まず、呼び手は**判定しない**こと(fail-close は呼び手の責任)。
func PriceLimitWidth(base float64) float64 {
	// NaN / ±Inf を弾く。`base <= 0` は NaN で false になり、続くループも全行 false に
	// なって**最終行(最大幅)へ落ちる** = 異常な入力に最も楽観的な答えを返す fail-open
	// だった。表の外の値は「不明」に倒す。
	if base <= 0 || math.IsNaN(base) || math.IsInf(base, 0) {
		return 0
	}
	for _, b := range priceLimitTable {
		if b.upto == 0 || base < b.upto {
			return b.width
		}
	}
	return 0
}

// LimitUp / LimitDown は基準値段からのストップ高 / ストップ安の値段。
// base が不正なら (0, false)。**ストップ安は 0 円未満にしない**(制限値幅が基準値段を
// 上回る低位株では 0 で止める)。
func LimitUp(base float64) (float64, bool) {
	w := PriceLimitWidth(base)
	if w <= 0 {
		return 0, false
	}
	return base + w, true
}

func LimitDown(base float64) (float64, bool) {
	w := PriceLimitWidth(base)
	if w <= 0 {
		return 0, false
	}
	// 0 円以下になる低位株。**0 円は東証に存在しない値段**なので値として返さず、
	// 「求められない」を返して呼び手に fail-close させる(実測: 6740 は直近 50 円・
	// データ内最安 34 円で、この分岐は現実的な距離にある)。
	if base-w <= 0 {
		return 0, false
	}
	return base - w, true
}
