// 値幅制限(ストップ高/安)。基準値段(前日終値または最終気配値段)の帯で決まる**階段**で、
// `TickSize` の呼値テーブルとは**別物**(流用禁止)。
//
// 出典と裏取り:
//   - **JPX 一次資料**(equities/trading/domestic/06.html)と全 34 帯・境界の向きまで一致。
//     全行が「◯◯円未満」表記なので `base < upto` がそのままの意味(100 は上の帯 = 50円)。
//     二次資料 5 本(立花 e支店 / 松井 / 三菱UFJ eスマート / 名証 / トレーダーズ)とも不一致ゼロ。
//   - **市場実測 2 件**(帯が別)が一致: 4704 は基準 6,851 → ストップ安 5,851
//     (幅 1,000)、同日 6904 は基準 460 → ストップ高 540(幅 80)。
//
// 🛑 **基準値段は前日終値とは限らない**。権利落ち日(配当・分割・無償割当)は落ち分だけ
// 下がり、特別気配で引ければ最終気配値段になる。**運用側の日足は分割未調整**なので、
// 素の前日終値を渡すと分割落ち日に帯が数段ずれる(3分割なら幅 700 → 300)。
// 呼び手は `ChainLinkSplits` を通した値を渡すこと。
//
// 🛑 **連続ストップ時の拡大は実装していない**。発動条件は一次資料にある(2営業日連続で
// ①ストップ配分も行われず売買高0株 ②午後立会終了時のみストップで成立し反対側に残数あり、
// のいずれか → 翌営業日から拡大)が、**倍率が公表されない**(随時マーケットニュース)ため。
// 該当銘柄は JPX が日次 CSV で公表しており頻度は機械的に数えられる。
// ⚠ 影響の向きは「悲観」ではない: 判定は「bid==ask **かつ制限値**」なので、
// 拡大日は表の値と観測値が一致せず**張り付きと判定されない = 約定させる(楽観)**。
// しかも成行も指値も約定しない規則なので**新規建ても消える** — 連続ストップ安は BNF 逆張りの
// 入口と強く相関するため、**サンプルが系統的に欠け、その符号は未知**。台帳にはそう書く。
// (ETF/ETN は拡大条件が緩く、重複上場外国銘柄は対象外。内国株以外に流用しない)
//
// 🛑 **返り値を等値比較しない**。細刻み銘柄(0.1 / 0.5 円)では `base ± width` に float 誤差が
// 乗る(実測: LimitDown(233.4) = 153.40000000000001)。等値比較は「張り付きを検出できない
// = 約定させる」= 楽観側に外れる。呼び手は `RoundToTickOf` を通すか許容誤差で比べること。
//
// 🛑 **発注経路から呼ぶ**。かつてここには「現時点でこの関数を呼ぶ実行経路は
// 無い。paper の未約定モデルで使う」と書いてあったが、**必要な呼び出し元を取り違えていた**。
// live で建てた直後、TP(25日線 6,435)が当日の上限 6,352 を超えていたため立花が
// 守りの発注ごと拒否し、約定済みの建玉を補償で閉じる往復を 5 回繰り返した。呼び出し元は:
//   - risk.EvaluatePriceLimit … SL が帯の外なら **建てない**(守りを board に置けない)
//   - risk.ProtectiveTakeProfitPlaceable … TP が帯の外なら **TP 脚だけ落として** SL を置く
// paper の未約定モデルは依然として未実装で、そちらでも使う予定。

// priceLimitBand は「基準値段が upto 未満なら幅は width」。upto=0 は上限なし(最終行)。
type priceLimitBand struct {
	upto  float64
	width float64
}

